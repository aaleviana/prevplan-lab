-- Exemplo separado para Oracle 12c+. Não é executado pela aplicação H2.
CREATE TABLE PLANOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(80) NOT NULL,
    DESCRICAO VARCHAR2(240) NOT NULL,
    CONTRIBUICAO_MENSAL NUMBER(12,2) NOT NULL,
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_PLANO_CONTRIBUICAO CHECK (CONTRIBUICAO_MENSAL > 0),
    CONSTRAINT CK_PLANO_ATIVO CHECK (ATIVO IN (0,1))
);

CREATE OR REPLACE PROCEDURE ATUALIZAR_CONTRIBUICAO (
    P_ID IN NUMBER,
    P_NOVO_VALOR IN NUMBER
) AS
BEGIN
    IF P_NOVO_VALOR IS NULL OR P_NOVO_VALOR <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'A contribuição deve ser maior que zero');
    END IF;
    UPDATE PLANOS SET CONTRIBUICAO_MENSAL = P_NOVO_VALOR WHERE ID = P_ID;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Plano não encontrado');
    END IF;
END;
/

SELECT ATIVO, COUNT(*) AS QUANTIDADE, ROUND(AVG(CONTRIBUICAO_MENSAL), 2) AS MEDIA
FROM PLANOS
GROUP BY ATIVO;
